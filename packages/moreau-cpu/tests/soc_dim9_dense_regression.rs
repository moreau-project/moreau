//! Regression: ill-conditioned dense SOC problem the CPU solver must solve.
//!
//! Problem: SOC dim=9, n=m=9, dense PD P, ill-conditioned dense A.

use moreau::{algebra::*, solver::*};

/// Build a dense n×n CSC matrix from row-major data.
fn dense_csc(n: usize, row_major: &[f64]) -> CscMatrix<f64> {
    assert_eq!(row_major.len(), n * n);
    // CSC: column pointers, row indices, values (column-major order)
    let mut colptr = vec![0usize; n + 1];
    let mut rowval = Vec::with_capacity(n * n);
    let mut nzval = Vec::with_capacity(n * n);
    for j in 0..n {
        colptr[j] = j * n;
        for i in 0..n {
            rowval.push(i);
            nzval.push(row_major[i * n + j]); // row_major[i][j] → column j
        }
    }
    colptr[n] = n * n;
    CscMatrix::new(n, n, colptr, rowval, nzval)
}

